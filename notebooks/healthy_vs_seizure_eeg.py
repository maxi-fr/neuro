@app.cell
def _(band_energy, connectome, dt_ms, eeg_healthy, eeg_seizure, np, plt):
    # Compute energy for healthy and seizure
    _energy_healthy = band_energy(eeg_healthy, dt_ms, band=(0.0, 50.0), normalize=True)
    _energy_seizure = band_energy(eeg_seizure, dt_ms, band=(0.0, 50.0), normalize=True)

    # Sort channels by energy in the seizure state to show which channels are strongest
    _order_seizure = np.argsort(_energy_seizure)[::-1]
    _top_n = 15
    _top_indices = _order_seizure[:_top_n]

    _top_labels = [str(connectome.channel_labels[_i]) for _i in _top_indices]
    _seizure_vals = _energy_seizure[_top_indices]
    _healthy_vals = _energy_healthy[_top_indices]

    _fig, _ax = plt.subplots(figsize=(8, 5.5), layout="constrained")

    # Plot grouped horizontal bar chart
    _y_pos = np.arange(_top_n)
    _height = 0.35

    _ax.barh(
        _y_pos + _height / 2, _seizure_vals[::-1], _height, label="Epileptic (Seizure)", color="#e91e63", alpha=0.9
    )
    _ax.barh(
        _y_pos - _height / 2, _healthy_vals[::-1], _height, label="Healthy (Background)", color="#3f51b5", alpha=0.6
    )

    _ax.set_yticks(_y_pos)
    _ax.set_yticklabels(_top_labels[::-1])
    _ax.set_xlabel("Normalized 0-50 Hz Energy (Max = 1.0)", fontweight="bold")
    _ax.set_title(f"Top {_top_n} EEG Channels ranked by Seizure Energy", fontsize=13, fontweight="bold")
    _ax.legend(loc="lower right")
    _ax.spines[["top", "right"]].set_visible(False)
    _ax.grid(visible=True, axis="x", linestyle="--", alpha=0.3)
    plt.show()
    return


