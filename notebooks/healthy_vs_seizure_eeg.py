@app.cell
def _(
    JansenRitParams,
    connectome,
    deterministic_toggle,
    divisor_slider,
    duration_slider,
    k_slider,
    lfp,
    np,
    replace,
    seed_slider,
    simulate_network,
    speed_slider,
    steady_window,
    transient_slider,
):
    # Setup network connectivity
    conn = replace(connectome, speed=speed_slider.value, delays=connectome.tract_lengths / speed_slider.value)
    conn = replace(conn, weights=conn.weights / divisor_slider.value)
    n_nodes = len(connectome.region_labels)

    # 1. Healthy Brain gains (A = 3.25 everywhere)
    a_gains_healthy = np.full(n_nodes, 3.25)

    # 2. Epileptic Brain gains (EZ/PZ increased)
    ez_names = ("lHC", "lPHC", "lAMYG")
    pz_names = ("lTCI", "lTCV")
    ez_idxs = [connectome.region_index[name] for name in ez_names]
    pz_idxs = [connectome.region_index[name] for name in pz_names]
    a_gains_seizure = np.full(n_nodes, 3.25)
    a_gains_seizure[ez_idxs] = 3.6
    a_gains_seizure[pz_idxs] = 3.4

    noise_sigma = 0.0 if deterministic_toggle.value else JansenRitParams().sigma

    # --- Run Healthy Brain Simulation ---
    params_healthy = JansenRitParams.from_config(
        {
            "connectome": conn,
            "dt": 1e-4,
            "params": {
                "A": a_gains_healthy,
                "sigma": noise_sigma,
                "K": k_slider.value,
            },
        }
    )
    t, x_traj_healthy = simulate_network(
        params=params_healthy,
        duration=float(duration_slider.value),
        dt=1e-4,
        seed=int(seed_slider.value),
    )
    y_healthy = lfp(x_traj_healthy)

    # --- Run Epileptic Brain Simulation ---
    params_seizure = JansenRitParams.from_config(
        {
            "connectome": conn,
            "dt": 1e-4,
            "params": {
                "A": a_gains_seizure,
                "sigma": noise_sigma,
                "K": k_slider.value,
            },
        }
    )
    _, x_traj_seizure = simulate_network(
        params=params_seizure,
        duration=float(duration_slider.value),
        dt=1e-4,
        seed=int(seed_slider.value),
    )
    y_seizure = lfp(x_traj_seizure)

    # Clean transients and project to EEG
    dt_ms = (t[1] - t[0]) * 1000.0
    transient_ms = float(transient_slider.value) * 1000.0

    y_healthy_steady = steady_window(y_healthy, dt_ms, transient_ms)
    y_seizure_steady = steady_window(y_seizure, dt_ms, transient_ms)

    eeg_healthy = conn.gain @ y_healthy_steady
    eeg_seizure = conn.gain @ y_seizure_steady

    t[round(transient_ms / dt_ms) :]
    return dt_ms, eeg_healthy, eeg_seizure


