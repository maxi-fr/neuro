@app.cell
def _(mo):
    mo.md(r"""
    ---
    ## 2. Criteria 1 & 6: Distance Distribution & Dimensionality Check

    ### Mathematical Formulation
    For any state-action query $z = [x, u]$, its $K$-nearest-neighbor distance relative to the training reference set $\mathcal{Z}_\text{ref}$ is:
    $$d_K(z) = \frac{1}{K} \sum_{i \in \mathcal{N}_K(z)} \|\tilde{z} - \tilde{z}_i\|_2$$
    Using the held-out in-distribution (ID) calibration set $\{d_K(z_i^\text{cal})\}_{i=1}^{N_\text{cal}}$, we define the empirical cumulative distribution function $\hat{F}_\text{ID}(d)$.
    The raw distance is mapped to an **ID Percentile**:
    $$q(z) = \hat{F}_\text{ID}(d_K(z)) \in [0, 1]$$

    ### Criterion 6: Check Distance Concentration
    In high-dimensional spaces ($D \approx 750$), distances can concentrate ($d_\max / d_\min \to 1$).
    We evaluate the **Coefficient of Variation**:
    $$CV = \frac{\operatorname{std}(d_K^\text{cal})}{\operatorname{mean}(d_K^\text{cal})}$$
    - **Desired ("Good")**: $CV > 0.05$ (meaningful relative spread across calibration points).
    - **Failure Mode**: $CV \to 0$ (all points are equidistant; metric collapses).

    ### Criterion 1: Does MPC Shift Off-Distribution?
    - **Desired ("Good")**: MPC queries fall predominantly within the in-distribution support zone ($q < 0.95$), overlapping with the ID calibration density.
    - **Concerning ("Shifted")**: MPC density shifts strongly to the right into the tail ($q > 0.95$ and $q > 0.99$).
    """)
    return


