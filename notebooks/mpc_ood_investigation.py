@app.cell
def _(mo):
    mo.md(r"""
    # 🎯 Detecting Distribution Shift for Learned Dynamics in MPC

    ## 1. Theoretical Foundations & Problem Formulation

    A learned surrogate dynamics model approximates the transition mapping:
    $$x_{t+1} = f_\theta(x_t, u_t)$$
    where $x_t \in \mathbb{R}^{n_x}$ represents the system state (here, structured time-frequency Observable Frames),
    and $u_t \in \mathbb{R}^m$ is the applied control current.

    ### Why State-Action Support Matters
    The training dataset is generated by a behavior policy inducing an empirical joint distribution:
    $$p_\text{train}(x, u) = p_\text{train}(x) \, p_\text{train}(u \mid x)$$
    Even when Random Amplitude Schedule (RAS) excitation spans its admissible control bounds $[-u_\max, u_\max]$,
    certain joint state-action configurations $(x, u)$ may occur rarely or not at all.

    During closed-loop model predictive control (MPC), the optimizer evaluates candidate control sequences:
    $$U = (u_t, u_{t+1}, \dots, u_{t+H-1})$$
    and recursively unrolls predictions:
    $$\hat{x}_{t+k+1} = f_\theta(\hat{x}_{t+k}, u_{t+k}), \quad k = 0, \dots, H-1$$

    ### The Central Question
    > **Are the state-action pairs $(x, u)$ queried by MPC similar to those observed during training?**

    If the optimizer drives the dynamics model into unsupported regions, the model may output unphysical hallucinations.
    The controller may exploit these errors to artificially minimize its cost function, leading to catastrophic failure
    when the selected control is applied to the real plant.
    """)
    return


