@app.cell
def _(mo):
    mo.md(r"""
    ---
    ## 5. Criteria 4 & 5: Validation Against Ground-Truth Dynamics Error

    ### Operational Relevance of Distribution Shift
    An OOD detection score is useful if and only if it is **predictive of model unreliability**.
    If a query has a high OOD score but the model predicts with high accuracy, the score is an overly conservative false alarm.
    Conversely, if the model incurs massive prediction error in regions marked "safe", the detector suffers from catastrophic false assurance.

    ### Criterion 4: One-Step Error Validation
    We compute the one-step dynamics prediction error on held-out trajectories:
    $$e_t = \|f_\theta(x_t, u_t) - x_{t+1}\|_2$$
    alongside its calibrated support percentile $q_t = q(x_t, u_t)$.
    - **Desired ("Good")**: Monotonic escalation $q_t \uparrow \implies e_t \uparrow$. Higher percentiles must exhibit larger average prediction errors.
    - **Failure Mode**: Flat error profile across percentile bins, indicating the distance metric fails to capture dynamics difficulty.

    ### Criterion 5: Multi-Step Recursive Rollout Validation
    We initialize the learned model from a true state $x_t$ and unroll it recursively over $H$ steps using true recorded controls:
    $$e_{t, k} = \|\hat{x}_{t+k} - x_{t+k}\|_2, \qquad E_H = \max_{1 \le k \le H} e_{t, k}$$
    alongside the maximum rollout support violation:
    $$Q_H = \max_{0 \le k < H} q(\hat{x}_{t+k}, u_{t+k})$$
    - **Desired ("Good")**: Positive correlation ($r > 0$) between $Q_H$ and $E_H$. When the optimizer proposes a trajectory with high $Q_H$, it should strongly indicate that the trajectory will diverge.
    """)
    return


