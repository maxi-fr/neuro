import json
import sqlite3
import sys
from contextlib import closing
from dataclasses import dataclass
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from matplotlib.ticker import MaxNLocator

from neuro.predictor.checkpoint import load_checkpoint

FIGURES = Path(__file__).resolve().parent
sys.path.insert(0, str(FIGURES.parent / "06_experiment_and_discussion"))
from offline_predictor_benchmark import CAMPAIGN, DIRECT_MLP, STUDIES, THESIS, style

TABLES = THESIS / "tables" / FIGURES.name
EXTRA_RUNS = {
    "observable_mlp": (DIRECT_MLP.parent,),
    "observable_cnn": (
        CAMPAIGN / "cnn/observable/baseline",
        CAMPAIGN / "cnn/observable/kt1_ablation",
    ),
}
TABLE_LAYOUTS = {
    "observable_mlp": ("rrrcllr", "Trial & History & Width & Layers & Activation & Output & Score"),
    "observable_cnn": ("rrrcrcllr", "Trial & History & Channels & Layers & Taper & Kernel & Head & Activation & Score"),
    "waveform_mlp": ("rrrrcllr", "Trial & History & Current & Width & Layers & Activation & Output & Score"),
    "waveform_cnn": (
        "rrrrcrrllr", "Trial & History & Current & Channels & Layers & Taper & Kernel & Head & Activation & Score"
    ),
}


@dataclass
class Trial:
    number: int
    state: str
    score: float | None
    params: dict
    directory: Path


def read_trials(directory: Path) -> list[Trial]:
    """Read the trial numbers, states, objectives, and decoded parameters from the archived study."""
    db = directory / "nn_predictor_sweep.db"
    with closing(sqlite3.connect(f"{db.as_uri()}?mode=ro&immutable=1", uri=True)) as conn:
        trials = {
            trial_id: Trial(number, state, value, {}, directory / f"trial_{number}")
            for trial_id, number, state, value in conn.execute(
                """
                SELECT trial_id, number, state, value
                FROM trials LEFT JOIN trial_values USING (trial_id)
                WHERE objective = 0 OR objective IS NULL
                ORDER BY number
                """
            )
        }
        for trial_id, name, value, distribution in conn.execute(
            "SELECT trial_id, param_name, param_value, distribution_json FROM trial_params"
        ):
            details = json.loads(distribution)
            if details["name"] == "CategoricalDistribution":
                value = details["attributes"]["choices"][int(value)]
            elif details["name"] == "IntDistribution":
                value = int(value)
            trials[trial_id].params[name] = value
    return list(trials.values())


def read_stats(directory: Path) -> dict:
    """Load the epoch-wise losses and checkpoint indices for a fitted network."""
    return json.loads((directory / "training_stats.json").read_text(encoding="utf-8"))


def neural_trials(key: str, directory: Path) -> list[Trial]:
    """Append the scored standalone architecture fits after the original Optuna trial numbers."""
    trials = read_trials(directory)
    for number, extra in enumerate(EXTRA_RUNS.get(key, ()), start=trials[-1].number + 1):
        params, _ = load_checkpoint(extra / "model.npz")
        stats = read_stats(extra)
        score = stats["frame_mse"] if key == "observable_cnn" else stats["val_loss"][stats["selected_epoch"]]
        trials.append(Trial(number, "COMPLETE", score, params, extra))
    return trials


def trial_cells(key: str, trial: Trial) -> list[str]:
    """Format the searched settings and the final score or incomplete trial status."""
    params = trial.params
    waveform = key.startswith("waveform")
    cells = [str(trial.number), str(params["n_y"])]
    if waveform:
        cells.append(str(20 * (params["n_u"] - 1)))
    cells.extend((str(params["hidden_size"]), str(params["depth"])))
    if key.endswith("mlp"):
        cells.extend((params["activation"], "Residual" if params.get("residual", True) else "Direct"))
    else:
        taper = f"{params['tapering_ratio']:.4f}" if params["depth"] > 1 else "---"
        kernel = params.get("kernel_size", 3)
        if not waveform:
            kernel = rf"\({kernel}\times{params['frequency_kernel_size']}\)"
        head = params.get("head_width") if params["head_depth"] else "Affine"
        head = {"geometric_mean": "Geom. mean", "trunk": "Last conv."}.get(head, head)
        cells.extend((taper, str(kernel), str(head), params["activation"]))
    score = f"{trial.score:.4f}" if trial.state == "COMPLETE" else {"PRUNED": "Pruned", "FAIL": "Failed"}[trial.state]
    return [*cells, score]


def save_trial_table(key: str, trials: list[Trial], winner: Trial) -> None:
    """Write a tabular with the selected architecture highlighted in bold."""
    columns, header = TABLE_LAYOUTS[key]
    rows = [
        "% Generated by predictor_search_appendix.py.",
        rf"\begin{{tabular}}{{@{{}}{columns}@{{}}}}",
        r"\toprule",
        header + r" \\",
        r"\midrule",
    ]
    for trial in trials:
        cells = trial_cells(key, trial)
        if trial is winner:
            cells = [rf"\textbf{{{cell}}}" for cell in cells]
        rows.append(" & ".join(cells) + r" \\")
    rows.extend((r"\bottomrule", r"\end{tabular}"))
    (TABLES / f"{key}_trials.tex").write_text("\n".join(rows) + "\n", encoding="utf-8")


def save_loss_curves(winners: list[tuple[str, Trial]]) -> None:
    """Plot each winner's logged loss with thesis notation, the full horizon, and the selected checkpoint."""
    fig, axes = plt.subplots(2, 2, figsize=style.figsize(height_in=3.85), layout="constrained")
    for ax, (label, trial) in zip(axes.flat, winners, strict=True):
        stats = read_stats(trial.directory)
        epochs = np.arange(1, len(stats["val_loss"]) + 1)
        eligible = stats["eligibility_start"]
        selected = stats["selected_epoch"]
        if not eligible <= selected < len(epochs):
            raise ValueError(f"Invalid checkpoint indices for {label}, trial {trial.number}.")
        train, = ax.plot(epochs, stats["train_loss"], color="C0", label="Training")
        validation, = ax.plot(epochs, stats["val_loss"], color="C1", label="Validation")
        full = ax.axvline(epochs[eligible], color="0.4", ls="--", lw=0.65, label="Full training loss")
        checkpoint, = ax.plot(
            epochs[selected], stats["val_loss"][selected], "o",
            mfc="white", mec="C1", ms=4, label="Selected checkpoint",
        )
        ax.set_title(f"{label}, trial {trial.number}")
        loss_label = (
            r"Log-power MSE $\mathcal{L}_{\mathrm{spec}}$"
            if label.startswith("Spectral")
            else r"Joint loss $\mathcal{L}$"
        )
        ax.set_ylabel(loss_label)
        ax.xaxis.set_major_locator(MaxNLocator(5, integer=True))
        ax.grid(axis="y")
    for ax in axes[-1]:
        ax.set_xlabel("Epoch")
    fig.legend(handles=(train, validation, full, checkpoint), loc="outside upper center", ncols=4, frameon=False)
    fig.savefig(FIGURES / "predictor_search_loss_curves.pdf")
    plt.close(fig)


def save_dmd_heatmaps(trials: list[Trial]) -> None:
    """Show minimum spectral loss and its range across ridge values using the thesis notation."""
    histories = sorted({trial.params["n_y"] for trial in trials})
    fractions = sorted({trial.params["dmd_energy"] for trial in trials})
    ridges = sorted({trial.params["dmd_lambda"] for trial in trials})
    scores = {
        (trial.params["n_y"], trial.params["dmd_energy"], trial.params["dmd_lambda"]): trial.score
        for trial in trials if trial.state == "COMPLETE"
    }
    if len(scores) != len(trials) or len(scores) != len(histories) * len(fractions) * len(ridges):
        raise ValueError("The archived DMDc grid is incomplete or has duplicate cells.")
    errors = np.array([[[scores[h, f, r] for r in ridges] for h in histories] for f in fractions])
    best = errors.min(axis=2)
    spread = np.ptp(errors, axis=2) * 1e7
    fig, axes = plt.subplots(1, 2, figsize=style.figsize(height_in=2.28), layout="constrained", sharey=True)
    titles = (
        r"Minimum validation $\mathcal{L}_{\mathrm{spec}}$",
        r"Range of $\mathcal{L}_{\mathrm{spec}}$ across $\lambda$ ($10^{-7}$)",
    )
    for ax, data, title in zip(axes, (best, spread), titles, strict=True):
        image = ax.imshow(data, origin="lower", aspect="auto", cmap="viridis", interpolation="nearest")
        ax.set_title(title)
        ax.set_xlabel(r"EEG history $n_{\mathrm{past},o}$ (frames)")
        ax.set_xticks(range(len(histories)), histories)
        ax.set_yticks(range(len(fractions)), [f"{fraction:g}" for fraction in fractions])
        fig.colorbar(image, ax=ax, pad=0.035).locator = MaxNLocator(5)
    axes[0].set_ylabel("Retained fraction")
    row, column = np.unravel_index(best.argmin(), best.shape)
    axes[0].plot(column, row, "o", ms=7, mfc="none", mec="white", mew=1)
    fig.savefig(FIGURES / "predictor_search_dmd_heatmaps.pdf")
    plt.close(fig)


def main() -> None:
    """Generate the appendix tables and figures from the archived architecture searches."""
    TABLES.mkdir(parents=True, exist_ok=True)
    winners = []
    for label, key, directory in STUDIES:
        if key == "observable_dmdc":
            save_dmd_heatmaps(read_trials(directory))
            continue
        trials = neural_trials(key, directory)
        winner = min((trial for trial in trials if trial.state == "COMPLETE"), key=lambda trial: trial.score)
        save_trial_table(key, trials, winner)
        winners.append((label, winner))
        print(f"{label}: {len(trials)} trials, winner {winner.number} ({winner.score:.4f})")
    save_loss_curves(winners)


if __name__ == "__main__":
    main()
